package com.nexusbank.transactions.app;

import com.nexusbank.transactions.accounts.accounts.Account;
import com.nexusbank.transactions.accounts.accounts.AccountStatus;
import com.nexusbank.transactions.accounts.accounts.AccountType;
import com.nexusbank.transactions.clients.accounts.accounts.client.AccountsClient;
import com.nexusbank.transactions.clients.accounts.accounts.client.GetAccountRequest;
import com.nexusbank.transactions.clients.iam.iam.users.User;
import com.nexusbank.transactions.prelude.NotFound;
import com.nexusbank.transactions.runtimeconfig.TransactionsApiClients;
import com.nexusbank.transactions.runtimeconfig.TransactionsApiRuntime;
import com.nexusbank.transactions.runtime.ClientOptions;
import com.nexusbank.transactions.runtime.Page;
import com.nexusbank.transactions.runtime.RequestContext;
import com.nexusbank.transactions.transactions.server.GetHistoryRequest;
import com.nexusbank.transactions.transactions.server.GetTransactionRequest;
import com.nexusbank.transactions.transactions.server.TransactionsService;
import com.nexusbank.transactions.transactions.server.TransferRequest;
import com.nexusbank.transactions.transactions.transactions.HistoryFilter;
import com.nexusbank.transactions.transactions.transactions.InsufficientFunds;
import com.nexusbank.transactions.transactions.transactions.Transaction;
import com.nexusbank.transactions.transactions.transactions.TransactionStatus;
import com.nexusbank.transactions.transactions.transactions.TransactionType;
import com.nexusbank.transactions.transactions.transactions.TransferInput;
import com.nexusbank.transactions.transactions.transactions.TransferReceipt;
import java.math.BigDecimal;
import java.time.Instant;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import java.util.Map;
import java.util.UUID;
import java.util.concurrent.ConcurrentHashMap;

/**
 * The transactions service: an in-memory ledger per account.
 *
 * <p>It is hand-written; everything it imports from {@code com.nexusbank.transactions} was
 * generated by Veld (service interface, models, errors and the clients of the services it
 * consumes). Callers are authenticated with the {@code iam} service, and accounts are checked with
 * the {@code accounts} service, which in turn calls this one for statements.
 */
public final class TransactionsServiceImpl implements TransactionsService {
  /** What the bearer hook returns; it arrives as {@code ctx.principal()}. */
  record Principal(User user, String token) {}

  private final Map<UUID, List<Transaction>> ledger = new ConcurrentHashMap<>();
  private final TransactionsApiRuntime runtime;

  /** Creates the service; the runtime config gives the URL of each service it calls. */
  public TransactionsServiceImpl(TransactionsApiRuntime runtime) {
    this.runtime = runtime;
  }

  /** The bearer hook: asks iam who the token belongs to. Null means unauthorized. */
  Object authenticate(String token, RequestContext ctx) {
    try {
      User user = TransactionsApiClients.create(runtime, ClientOptions.builder().bearer(() -> token).build())
              .iam()
              .getProfile();
      return new Principal(user, token);
    } catch (com.nexusbank.transactions.clients.iam.prelude.Unauthorized e) {
      return null;
    }
  }

  private static Principal principal(RequestContext ctx) {
    return (Principal) ctx.principal();
  }

  /** The account, fetched from the accounts service with the caller's token. */
  private com.nexusbank.transactions.clients.accounts.accounts.accounts.Account account(
      Principal p, UUID id) {
    AccountsClient accounts =
        TransactionsApiClients.create(runtime, ClientOptions.builder().bearer(p::token).build())
            .accounts();
    try {
      return accounts.getAccount(new GetAccountRequest(id));
    } catch (com.nexusbank.transactions.clients.accounts.prelude.NotFound e) {
      // The accounts service's typed NotFound becomes this service's own NotFound.
      throw new NotFound(new NotFound.Data("account"));
    }
  }

  /** The first time an account is seen, its balance becomes an opening credit. */
  private List<Transaction> ledgerOf(com.nexusbank.transactions.clients.accounts.accounts.accounts.Account a) {
    return ledger.computeIfAbsent(a.id(), id -> {
      List<Transaction> list = new ArrayList<>();
      list.add(entry(id, TransactionType.CREDIT, a.balance(), a.currency(), "Opening balance"));
      return list;
    });
  }

  private static Transaction entry(
      UUID accountId, TransactionType type, BigDecimal amount, String currency, String description) {
    String reference = "TX-" + UUID.randomUUID().toString().substring(0, 8).toUpperCase();
    return new Transaction(
        UUID.randomUUID(),
        accountId,
        type,
        TransactionStatus.COMPLETED,
        amount,
        currency,
        description,
        reference,
        Instant.now());
  }

  private static BigDecimal balanceOf(List<Transaction> list) {
    BigDecimal sum = BigDecimal.ZERO;
    for (Transaction t : list) {
      if (t.status() != TransactionStatus.COMPLETED) continue;
      sum = t.type() == TransactionType.CREDIT ? sum.add(t.amount()) : sum.subtract(t.amount());
    }
    return sum;
  }

  @Override
  public Page<Transaction> getHistory(GetHistoryRequest request, RequestContext ctx) {
    var account = account(principal(ctx), request.accountId());
    HistoryFilter filter = request.query();
    int page = filter.page() == null ? 1 : filter.page();
    int size = filter.size() == null ? 20 : filter.size();
    List<Transaction> all;
    synchronized (this) {
      all = new ArrayList<>(ledgerOf(account));
    }
    List<Transaction> matching =
        all.stream()
            .filter(t -> filter.status() == null || t.status() == filter.status())
            .filter(t -> filter.type() == null || t.type() == filter.type())
            .sorted(Comparator.comparing(Transaction::createdAt).reversed())
            .toList();
    int from = Math.min((page - 1) * size, matching.size());
    int to = Math.min(from + size, matching.size());
    return new Page<>(matching.subList(from, to), matching.size(), page, size);
  }

  @Override
  public Transaction getTransaction(GetTransactionRequest request, RequestContext ctx) {
    Principal p = principal(ctx);
    for (List<Transaction> list : ledger.values()) {
      for (Transaction t : List.copyOf(list)) {
        if (t.id().equals(request.id())) {
          account(p, t.accountId()); // only the owner of the account may read its transactions
          return t;
        }
      }
    }
    throw new NotFound(new NotFound.Data("transaction"));
  }

  @Override
  public synchronized TransferReceipt transfer(TransferRequest request, RequestContext ctx) {
    TransferInput in = request.body();
    var account = account(principal(ctx), in.fromAccountId());
    List<Transaction> list = ledgerOf(account);
    BigDecimal available =
        account.status() == com.nexusbank.transactions.clients.accounts.accounts.accounts.AccountStatus.ACTIVE
            ? balanceOf(list)
            : BigDecimal.ZERO;
    if (in.amount().signum() <= 0 || in.amount().compareTo(available) > 0) {
      throw new InsufficientFunds(new InsufficientFunds.Data(available, in.amount()));
    }
    String note = in.description() == null ? "Transfer to " + in.toIban() : in.description();
    Transaction debit = entry(account.id(), TransactionType.TRANSFER, in.amount(), in.currency(), note);
    list.add(debit);
    // The receipt carries the account with its new balance. The `Account` type here is the one
    // generated for this service's own contract; the accounts client has a structurally equal copy.
    Account source =
        new Account(
            account.id(),
            account.userId(),
            AccountType.valueOf(account.type().name()),
            AccountStatus.valueOf(account.status().name()),
            account.name(),
            account.currency(),
            balanceOf(list),
            account.iban(),
            account.createdAt());
    return new TransferReceipt(debit, source);
  }
}
