// overwriteUnmanagedFlag is the flag that lets generation replace files the
// manifest does not list.
const overwriteUnmanagedFlag = "--overwrite-unmanaged"

// readmeTitle opens the README written into every output directory.
const readmeTitle = "# Generated by Veld"

// generatedMarkers identify files that a Veld without manifests wrote: the
// header emitters put on generated sources, and the README title.
var generatedMarkers = [][]byte{[]byte("AUTO-GENERATED BY VELD"), []byte(readmeTitle)}

// markerWindow is how far into a file the markers are looked for.
const markerWindow = 512

// writtenByVeld reports whether a file in pre-manifest output carries a
// generated marker near its start, so generation may take it over.
func writtenByVeld(existing []byte) bool {
	head := existing[:min(len(existing), markerWindow)]
	for _, m := range generatedMarkers {
		if bytes.Contains(head, m) {
			return true
		}
	}
	return false
}

// genMode holds the switches that shape one generation run.
type genMode struct {
	incremental        bool
	dryRun             bool
	overwriteUnmanaged bool
	serviceSDK         bool
}

// genResult is what a generation run produced.
type genResult struct {
	modules   []string      // emitted modules (workspace: entry names)
	veldFiles []string      // contract files read
	changes   []diff.Change // contract changes against the lock
	plan      *output.Plan  // nil when nothing was emitted
}

// genRun is one generation in progress. Emitters write only into staging
// directories obtained from sess; side effects on the config directory (cache,
// lock) are queued in after and run only once the output is committed.
type genRun struct {
	sess     *output.Session
	dryRun   bool
	emitters []string
	after    []func()
}

// generate runs one complete generation through the staged writer (ADR-007):
// compile and emit into staging, plan against each output directory's
// manifest, then, unless dry-running, apply the plan and only then save the
// cache and lock. If any step fails, every output directory, the cache and
// the lock are left exactly as they were.
func generate(rc config.ResolvedConfig, flags config.FlagOverrides, opts emitter.EmitOptions, mode genMode) (genResult, error) {
	sess, err := output.NewSession(outputPolicy(rc))
	if err != nil {
		return genResult{}, err
	}
	defer func() {
		if err := sess.Close(); err != nil {
			fmt.Fprintf(os.Stderr, yellow("warning: ")+"%v\n", err)
		}
	}()
	run := &genRun{sess: sess, dryRun: mode.dryRun}

	var res genResult
	if len(rc.Workspace) > 0 {
		res.modules, res.veldFiles, res.changes, err = runWorkspaceGenerate(run, rc, flags, opts, mode.serviceSDK)
	} else {
		res.modules, res.veldFiles, res.changes, err = runGenerate(run, rc, mode.incremental, opts)
	}
	if err != nil {
		return res, err
	}

	if len(sess.Dirs()) > 0 {
		res.plan, err = sess.Plan(output.Options{
			VeldVersion:        Version,
			Emitters:           run.emitters,
			OverwriteUnmanaged: mode.overwriteUnmanaged,
			Partial:            mode.incremental,
			Adopt:              writtenByVeld,
		})
		var conflict *output.ConflictError
		if errors.As(err, &conflict) {
			return res, fmt.Errorf("%w\nNothing was written. Move these files out of the output directory, "+
				"or run `veld generate %s` once to let Veld replace them", err, overwriteUnmanagedFlag)
		}
		if err != nil {
			return res, err
		}
	}
	if mode.dryRun {
		return res, nil
	}
	if res.plan != nil {
		if err := res.plan.Apply(); err != nil {
			return res, fmt.Errorf("write generated output: %w", err)
		}
	}
	for _, f := range run.after {
		f()
	}
	return res, nil
}

// afterCommit queues f to run once the output has been written.
func (r *genRun) afterCommit(f func()) {
	r.after = append(r.after, f)
}

// stage returns rc's backend and frontend output directories mapped to
// staging directories, plus the distinct staged directories. Every directory
// is checked against the output policy here, before any emitter runs. (rc.Out
// is only the fallback both are resolved from, and rc.OutputDirs lists every
// workspace directory when rc belongs to a workspace entry, so neither is used.)
func (r *genRun) stage(rc config.ResolvedConfig) (backend, frontend string, dirs []string, err error) {
	if backend, err = r.sess.Stage(rc.BackendOut); err != nil {
		return "", "", nil, err
	}
	if frontend, err = r.sess.Stage(rc.FrontendOut); err != nil {
		return "", "", nil, err
	}
	dirs = []string{backend}
	if frontend != backend {
		dirs = append(dirs, frontend)
	}
	return backend, frontend, dirs, nil
}

// stagedDir returns the staging directory for an output directory.
func (r *genRun) stagedDir(dir string) (string, error) {
	return r.sess.Stage(dir)
}

// emit runs rc's backend and frontend emitters into staging, then writes the
// generated README into every staged output directory.
func (r *genRun) emit(rc config.ResolvedConfig, backendAST, frontendAST ast.AST, opts emitter.EmitOptions) error {
	backendOut, frontendOut, dirs, err := r.stage(rc)
	if err != nil {
		return err
	}

	backendOrTool, _, err := emitter.GetBackendOrTool(rc.Backend)
	if err != nil {
		return err
	}
	if err := backendOrTool.Emit(backendAST, backendOut, opts); err != nil {
		return fmt.Errorf("%s emitter: %w", rc.Backend, err)
	}
	r.emitters = append(r.emitters, rc.Backend)

	// --frontend=typescript --frontend-framework=react routes to the react emitter.
	frontendName := rc.Frontend
	if opts.FrontendFramework != "" && (frontendName == "typescript" || frontendName == "javascript") {
		frontendName = opts.FrontendFramework
	}
	frontend, err := emitter.GetFrontend(frontendName)
	if err != nil {
		return err
	}
	if frontend != nil {
		if err := frontend.Emit(frontendAST, frontendOut, opts); err != nil {
			return fmt.Errorf("%s emitter: %w", rc.Frontend, err)
		}
		r.emitters = append(r.emitters, frontendName)
	}

	for _, dir := range dirs {
		if err := writeGeneratedReadme(dir, backendAST); err != nil {
			return err
		}
	}
	return nil
}

// outputPolicy lists the directories no output directory may equal or
// contain: the config directory, every input directory and the working
// directory (home and the filesystem root are always protected).
func outputPolicy(rc config.ResolvedConfig) output.Policy {
	prot := []output.Protected{{Label: "config directory", Path: rc.ConfigDir}}
	if rc.Input != "" {
		prot = append(prot, output.Protected{Label: "contract directory", Path: filepath.Dir(rc.Input)})
	}
	for _, e := range rc.Workspace {
		if e.Input == "" {
			continue
		}
		in := e.Input
		if !filepath.IsAbs(in) {
			in = filepath.Join(rc.ConfigDir, in)
		}
		prot = append(prot, output.Protected{Label: "contract directory of " + e.Name, Path: filepath.Dir(in)})
	}
	if cwd, err := os.Getwd(); err == nil {
		prot = append(prot, output.Protected{Label: "working directory", Path: cwd})
	}
	return output.Policy{Protected: prot}
}

// printPlan shows, per resolved output directory, what a run would change.
func printPlan(plan *output.Plan) {
	if plan == nil {
		fmt.Println(dim("  nothing to generate"))
		return
	}
	for _, d := range plan.Dirs {
		fmt.Printf("  %s\n", bold(d.Dir))
		for _, p := range d.Create {
			fmt.Printf("    %s create  %s\n", green("+"), p)
		}
		for _, p := range d.Update {
			fmt.Printf("    %s update  %s\n", yellow("~"), p)
		}
		for _, p := range d.Delete {
			fmt.Printf("    %s delete  %s\n", red("-"), p)
		}
		for _, p := range d.Keep {
			fmt.Printf("    %s keep    %s %s\n", yellow("!"), p, dim("(edited since Veld wrote it; no longer managed)"))
		}
		if n := len(d.Unchanged); n > 0 {
			fmt.Printf("    %s\n", dim(fmt.Sprintf("%d file(s) unchanged", n)))
		}
	}
}

// printKept warns about stale generated files left in place because they
// were edited by hand.
func printKept(plan *output.Plan) {
	if plan == nil {
		return
	}
	for _, d := range plan.Dirs {
		for _, p := range d.Keep {
			fmt.Fprintf(os.Stderr, yellow("⚠")+"  %s is no longer generated but was edited by hand; left in place\n",
				filepath.Join(d.Dir, filepath.FromSlash(p)))
		}
	}
}
