//! The `java` generator through the real `veld generate`: a server target and a client target.
//!
//! The generated sources are compiled with `javac --release 17 -Xlint:all -Werror` when a JDK is
//! on PATH; without one that step is skipped with a message, unless `VELD_REQUIRE_TOOLCHAINS=1`.
#![allow(clippy::unwrap_used, clippy::expect_used, clippy::panic)]
mod common;

use std::fs;
use std::path::Path;
use std::process::Command;

use common::*;
use predicates::prelude::*;
use tempfile::tempdir;

const CONTRACT: &str = r#"/// A greeting.
model Greeting {
  message: string
}

/// Says hello.
service Hello at "/hello" {
  /// Greets.
  get "/{name}" greet(name: string) -> Greeting | NotFound
}
"#;

const TOML: &str = r#"[project]
name = "demo"

[[targets]]
name = "api"
role = "server"
emitter = "java"
out = "gen/server"

[targets.options]
package = "com.example.hello"

[[targets]]
name = "sdk"
role = "client"
emitter = "java"
out = "gen/client"

[targets.options]
package = "com.example.hello.client"
"#;

fn project(dir: &Path) {
    write(dir, "contracts/hello.veld", CONTRACT);
    write(dir, "veld.toml", TOML);
}

fn javac_available() -> bool {
    let ok = Command::new("javac")
        .arg("--version")
        .output()
        .is_ok_and(|o| o.status.success());
    if !ok {
        assert!(
            std::env::var("VELD_REQUIRE_TOOLCHAINS").as_deref() != Ok("1"),
            "VELD_REQUIRE_TOOLCHAINS is set but javac is missing"
        );
        eprintln!("skipped javac step: no JDK on PATH");
    }
    ok
}

#[test]
fn generates_a_java_server_and_a_java_client() {
    let tmp = tempdir().unwrap();
    project(tmp.path());
    veld(tmp.path())
        .arg("generate")
        .assert()
        .success()
        .stdout(predicate::str::contains("api -> gen/server:"))
        .stdout(predicate::str::contains("sdk -> gen/client:"));
    let files = tree(tmp.path());
    let has = |p: &str| files.contains_key(p);
    // server: models, the service interface, the handler, the JDK adapter, the runtime
    assert!(
        has("gen/server/com/example/hello/demo/hello/Greeting.java"),
        "{:?}",
        files.keys().collect::<Vec<_>>()
    );
    assert!(has(
        "gen/server/com/example/hello/demo/server/HelloService.java"
    ));
    assert!(has(
        "gen/server/com/example/hello/demo/server/HelloHandler.java"
    ));
    assert!(has(
        "gen/server/com/example/hello/adapters/JdkHttpServerAdapter.java"
    ));
    assert!(has("gen/server/com/example/hello/runtime/Veld.java"));
    assert!(
        !has("gen/server/com/example/hello/adapters/SpringAdapter.java"),
        "Spring only on request"
    );
    // client: models and the client class, no server code
    assert!(has(
        "gen/client/com/example/hello/client/demo/client/HelloClient.java"
    ));
    assert!(
        !files
            .keys()
            .any(|k| k.starts_with("gen/client/") && k.contains("/adapters/"))
    );
    assert!(
        has("gen/server/.veld-manifest.json"),
        "written through the staged writer"
    );
    let text = |p: &str| String::from_utf8(files[p].clone()).unwrap();
    assert!(
        text("gen/server/com/example/hello/demo/hello/Greeting.java").starts_with(
            "// Code generated by veld. DO NOT EDIT.\npackage com.example.hello.demo.hello;"
        )
    );

    // Output is deterministic: a second run changes nothing.
    veld(tmp.path()).arg("generate").assert().success();
    assert_eq!(files, tree(tmp.path()));
}

#[test]
fn generated_java_compiles_without_warnings() {
    if !javac_available() {
        return;
    }
    let tmp = tempdir().unwrap();
    project(tmp.path());
    veld(tmp.path()).arg("generate").assert().success();
    let mut sources = Vec::new();
    for (path, _) in tree(&tmp.path().join("gen")) {
        if path.ends_with(".java") {
            sources.push(format!("gen/{path}"));
        }
    }
    fs::write(tmp.path().join("sources.txt"), sources.join("\n")).unwrap();
    let out = Command::new("javac")
        .args([
            "--release",
            "17",
            "-Xlint:all",
            "-Werror",
            "-d",
            "classes",
            "@sources.txt",
        ])
        .current_dir(tmp.path())
        .output()
        .unwrap();
    assert!(
        out.status.success(),
        "javac failed:\n{}",
        String::from_utf8_lossy(&out.stderr)
    );
}

#[test]
fn spring_framework_adds_the_spring_adapter() {
    let tmp = tempdir().unwrap();
    project(tmp.path());
    let toml = TOML.replacen(
        "role = \"server\"\n",
        "role = \"server\"\nframework = \"spring\"\n",
        1,
    );
    write(tmp.path(), "veld.toml", &toml);
    veld(tmp.path()).arg("generate").assert().success();
    assert!(
        tree(tmp.path()).contains_key("gen/server/com/example/hello/adapters/SpringAdapter.java")
    );
}

#[test]
fn a_bad_package_is_reported_not_generated() {
    let tmp = tempdir().unwrap();
    project(tmp.path());
    write(
        tmp.path(),
        "veld.toml",
        &TOML.replace("com.example.hello.client", "1not.valid"),
    );
    veld(tmp.path())
        .arg("generate")
        .assert()
        .failure()
        .stderr(predicate::str::contains("E0802"));
    assert!(
        !tree(tmp.path()).keys().any(|k| k.starts_with("gen/")),
        "nothing is written on failure"
    );
}
