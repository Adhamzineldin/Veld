pub const PROTOCOL_TS: &str = r#"// The Veld plugin protocol (spec/plugin-protocol.md), version 1. You normally do not edit this file.
//
// stdout carries the protocol and nothing else: log with `log()`, which writes to stderr.
// Veld forwards stderr lines with a `[plugin:{{name}}]` prefix.

import { createInterface } from "node:readline";
import type { Feature, GenerateRequest, GenerateResult, PluginHello, Role } from "./ir";

/** What `generate` returns: the files and optional diagnostics. The `type` tag is added for you. */
export type Generated = Omit<GenerateResult, "type">;

export interface Plugin {
  name: string;
  version: string;
  roles: Role[];
  /** The IR features this plugin implements. Anything else is reported by Veld as E0801. */
  capabilities: Feature[];
  /** JSON Schema for `[targets.options]`, optional. */
  optionsSchema?: unknown;
  generate(request: GenerateRequest): Generated | Promise<Generated>;
}

export function log(message: string): void {
  process.stderr.write(`${message}\n`);
}

function send(message: unknown): void {
  process.stdout.write(`${JSON.stringify(message)}\n`);
}

function hello(plugin: Plugin): PluginHello {
  const reply: PluginHello = {
    type: "hello",
    protocol: "1",
    name: plugin.name,
    version: plugin.version,
    roles: plugin.roles,
    capabilities: plugin.capabilities,
  };
  if (plugin.optionsSchema !== undefined) reply.options_schema = plugin.optionsSchema;
  return reply;
}

async function handle(plugin: Plugin, line: string): Promise<void> {
  const message = JSON.parse(line) as { type?: string };
  if (message.type === "hello") {
    send(hello(plugin));
  } else if (message.type === "generate") {
    try {
      const result = await plugin.generate(message as GenerateRequest);
      send({ type: "result", diagnostics: [], ...result });
    } catch (error) {
      const text = error instanceof Error ? error.message : String(error);
      send({ type: "result", files: [], diagnostics: [{ code: "E0899", severity: "error", message: text }] });
    }
  } else {
    log(`ignoring a message of unknown type: ${String(message.type)}`);
  }
}

/** Runs the handshake and generate loop until Veld closes stdin. */
export function serve(plugin: Plugin): void {
  const lines = createInterface({ input: process.stdin, crlfDelay: Infinity });
  let queue: Promise<void> = Promise.resolve();
  lines.on("line", (line) => {
    if (line.trim() === "") return;
    queue = queue.then(() => handle(plugin, line)).catch((error: unknown) => {
      log(`fatal: ${String(error)}`);
      process.exit(1);
    });
  });
  lines.on("close", () => {
    void queue.then(() => process.exit(0));
  });
}
"#;

