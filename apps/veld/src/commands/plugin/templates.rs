pub const GENERATE_TS: &str = r#"// Your generator. Veld calls `generate` once per target with the whole IR (see ir.d.ts and
// spec/ir.md) and the services this target is for.
//
// Rules (the host enforces them, and `veld plugin test` checks them):
//   - Embed every `sig` of the IR VERBATIM (declarations and endpoints). Never compute one.
//   - Output must be deterministic: no timestamps, absolute paths or random values.
//   - File paths are relative, use `/`, and never contain `..`.
//   - Only declare a capability in `capabilities` after you implemented it.

import type { Decl, GenerateRequest, PluginFile } from "./ir";
import type { Generated, Plugin } from "./protocol";

export const plugin: Plugin = {
  name: "{{name}}",
  version: "0.1.0",
  roles: ["client"],
  // TODO({{name}}): add features one at a time, for example "constraints", "auth", "unions".
  capabilities: [],
  generate,
};

function generate(request: GenerateRequest): Generated {
  const files: PluginFile[] = [];
  // TODO({{name}}): only emit what the selected services reach, instead of every declaration.
  for (const decl of request.ir.decls) {
    files.push({ path: `types/${fileName(decl.qualified)}.txt`, content: emitDecl(decl) });
  }
  for (const id of request.services) {
    const service = request.ir.services[id];
    if (service === undefined) continue;
    const lines = [`// TODO({{name}}): emit the ${service.name} service`];
    for (const endpoint of service.endpoints) {
      lines.push(`// ${endpoint.method} ${endpoint.path} ${endpoint.name} sig: ${endpoint.sig}`);
    }
    files.push({ path: `services/${id}_${fileName(service.name)}.txt`, content: `${lines.join("\n")}\n` });
  }
  return { files };
}

/** One file per declaration. TODO({{name}}): replace with real output for models, enums, ... */
function emitDecl(decl: Decl): string {
  const lines = [`// TODO({{name}}): emit the ${decl.kind} ${decl.name}`, `// sig: ${decl.sig}`];
  if (decl.kind === "model") {
    for (const field of decl.fields) lines.push(`//   ${field.name}${field.optional ? "?" : ""}`);
  }
  return `${lines.join("\n")}\n`;
}

function fileName(qualified: string): string {
  return qualified.replace(/[^A-Za-z0-9_-]/g, "_");
}
"#;

pub const README_MD: &str = r#"# veld-emit-{{name}}

A Veld emitter plugin for {{name}}, written in TypeScript with no runtime dependencies.
Veld starts it as a child process and talks to it over JSON lines
(see `spec/plugin-protocol.md` in the Veld repository).

## Develop

```sh
npm install        # installs typescript and @types/node (dev only)
npm run build      # compiles src/ to dist/
npm test           # veld plugin test node dist/main.js
```

- `src/generate.ts` is your generator. Start there.
- `src/protocol.ts` is the handshake and generate loop. You normally do not edit it.
- `src/ir.d.ts` holds the types of the IR and the protocol messages. It is generated from
  Veld's own definitions, so do not edit it. Update it by running `veld plugin new` again in a
  scratch directory and copying the file.

## Rules your plugin must follow

1. Embed every `sig` of the IR **verbatim**: declarations and endpoints. Never compute a signature.
2. Be **deterministic**: two runs on the same IR give the same files.
3. Use **relative `/` paths** without `..`. Veld refuses anything else (`E0707`).
4. Declare only the capabilities you implemented. Veld reports `E0801` for the rest.
5. Write logs to **stderr**. stdout is the protocol.

`veld plugin test node dist/main.js` checks the handshake, path safety, determinism across two
runs and signature embedding.

## Use it in a project

Copy `veld.plugin.toml` into the project's `veld.toml` and add a target with
`emitter = "plugin:{{name}}"`.
"#;

