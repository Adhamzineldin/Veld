// Regenerates src/pages/docs/cliHelp.ts from the real `veld --help` output.
// Usage: node scripts/gen-cli-help.mjs [path/to/veld]   (default: ../target/debug/veld)
import { execFileSync } from 'node:child_process';
import { writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..', '..');
let bin = process.argv[2] ?? resolve(root, 'target/debug/veld');
if (!existsSync(bin) && existsSync(`${bin}.exe`)) bin = `${bin}.exe`;

const run = (args) =>
  execFileSync(bin, [...args, '--help'], { encoding: 'utf8' })
    .replace(/\r\n/g, '\n')
    .replace(/veld\.exe/g, 'veld')
    .trimEnd();

const commands = [
  [],
  ['init'], ['check'], ['generate'], ['clean'], ['setup'], ['fmt'], ['diff'],
  ['export'], ['export', 'openapi'], ['export', 'ir'],
  ['plugin'], ['plugin', 'new'], ['plugin', 'test'],
  ['add'], ['install'], ['publish'], ['login'], ['logout'],
];

const entries = commands.map((c) => [['veld', ...c].join(' '), run(c)]);
const version = execFileSync(bin, ['--version'], { encoding: 'utf8' }).trim();
const body = entries.map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n');
writeFileSync(
  resolve(here, '../src/pages/docs/cliHelp.ts'),
  `// Generated by scripts/gen-cli-help.mjs from the real \`veld --help\` output. Do not edit.\nexport const cliVersion = ${JSON.stringify(version)};\n\nexport const cliHelp: Record<string, string> = {\n${body}\n};\n`,
);
console.log(`wrote ${entries.length} help texts from ${version}`);
