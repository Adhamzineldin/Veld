package node

// respond.go — emits routes/_respond.ts, the one error responder every route
// handler calls from its catch block (F-NODE-10).

import (
	"fmt"
	"os"
	"path/filepath"

	"github.com/Adhamzineldin/Veld/internal/ast"
	nodestrategy "github.com/Adhamzineldin/Veld/internal/emitter/backend/node/strategy"
)

// respondModule is the routes-relative module that exports sendError.
const respondModule = "./_respond"

// emitRespondHelper writes routes/_respond.ts when any module has an HTTP route.
func (e *NodeEmitter) emitRespondHelper(a ast.AST, outDir string, strat nodestrategy.NodeFrameworkStrategy) error {
	if !hasHTTPRoute(a) {
		return nil
	}
	dir := filepath.Join(outDir, "routes")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	src := fmt.Sprintf(`// AUTO-GENERATED BY VELD — DO NOT EDIT

/**
 * Sends the JSON error response for anything a route handler throws.
 *
 * An error that declares an HTTP status (err.status or err.statusCode, 400 to
 * 599) keeps that status and its string code. For 4xx statuses the message is
 * returned as well. Everything else becomes a 500 with a fixed message, so
 * internal details such as database errors, file paths or credentials never
 * reach the client; those errors are logged on the server instead.
 */
export function sendError(res: %s, err: unknown): void {
  const e = (typeof err === 'object' && err !== null ? err : {}) as {
    status?: unknown;
    statusCode?: unknown;
    message?: unknown;
    code?: unknown;
  };
  const declared = Number(e.status ?? e.statusCode);
  const hasStatus = Number.isInteger(declared) && declared >= 400 && declared <= 599;
  const status = hasStatus ? declared : 500;
  const body: Record<string, string> = { error: 'Internal Server Error' };
  if (status < 500 && typeof e.message === 'string' && e.message !== '') {
    body.error = e.message;
  }
  if (hasStatus && typeof e.code === 'string' && e.code !== '') {
    body.code = e.code;
  }
  if (status >= 500) {
    console.error('[veld] request failed with status ' + status + ':', err);
  }
  res.status(status).json(body);
}
`, strat.ResponseType())
	return os.WriteFile(filepath.Join(dir, "_respond.ts"), []byte(src), 0o644)
}

// hasHTTPRoute reports whether any module has a non-WebSocket action.
func hasHTTPRoute(a ast.AST) bool {
	for _, mod := range a.Modules {
		for _, act := range mod.Actions {
			if act.Method != "WS" {
				return true
			}
		}
	}
	return false
}
