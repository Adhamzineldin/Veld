//! Generator traits, requests, diagnostics and the capability gate.

use std::collections::BTreeSet;

use serde::de::DeserializeOwned;
use veld_ir::{DeclKind, Feature, Ir, Origin, ServiceId};

use crate::FileSet;
use crate::profile::{FrameworkInfo, LanguageInfo, Offer, Profile, strip_profile_keys};

/// Which side of the wire a generator produces.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum Role {
    Server,
    Client,
}

impl Role {
    #[must_use]
    pub fn name(self) -> &'static str {
        match self {
            Role::Server => "server",
            Role::Client => "client",
        }
    }
}

/// The features a generator supports for one role.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Capabilities(pub BTreeSet<Feature>);

impl Capabilities {
    /// Everything except the listed features.
    #[must_use]
    pub fn all_except(unsupported: &[Feature]) -> Self {
        Self(
            Feature::ALL
                .into_iter()
                .filter(|f| !unsupported.contains(f))
                .collect(),
        )
    }

    #[must_use]
    pub fn supports(&self, feature: Feature) -> bool {
        self.0.contains(&feature)
    }
}

/// What to generate.
#[derive(Debug, Clone)]
pub struct GenRequest<'a> {
    pub ir: &'a Ir,
    pub role: Role,
    /// Services generated by this request.
    pub services: Vec<ServiceId>,
    /// Services whose clients are generated alongside (server role).
    pub consumes: Vec<ServiceId>,
    pub framework: Option<String>,
}

/// A problem found while generating.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GenDiagnostic {
    pub code: &'static str,
    pub message: String,
    pub origin: Option<Origin>,
}

impl GenDiagnostic {
    #[must_use]
    pub fn new(code: &'static str, message: impl Into<String>) -> Self {
        Self {
            code,
            message: message.into(),
            origin: None,
        }
    }
}

/// A code generator with typed options.
pub trait Generator {
    type Options: DeserializeOwned + Default;

    fn id(&self) -> &'static str;
    fn roles(&self) -> &'static [Role];
    /// The frameworks of `role`, derived from the generator's adapter registry.
    fn frameworks(&self, role: Role) -> Vec<FrameworkInfo>;
    /// The language and its supported versions, when the generator has versioned output.
    fn language(&self) -> Option<LanguageInfo> {
        None
    }
    fn capabilities(&self, role: Role) -> Capabilities;
    /// `profile` is already validated by the core (`resolve_profile`).
    fn generate(
        &self,
        req: &GenRequest<'_>,
        opts: &Self::Options,
        profile: &Profile,
    ) -> Result<FileSet, Vec<GenDiagnostic>>;
}

/// Object-safe form of [`Generator`]: options arrive as JSON.
pub trait DynGenerator {
    fn id(&self) -> &'static str;
    fn roles(&self) -> &'static [Role];
    fn frameworks(&self, role: Role) -> Vec<FrameworkInfo>;
    fn language(&self) -> Option<LanguageInfo> {
        None
    }
    fn capabilities(&self, role: Role) -> Capabilities;
    fn generate_dyn(
        &self,
        req: &GenRequest<'_>,
        opts: &serde_json::Value,
    ) -> Result<FileSet, Vec<GenDiagnostic>>;
}

/// `E0803` when `req.framework` is not one of the generator's `frameworks(role)`. Every role is
/// checked here, so a generator cannot silently ignore a value it does not understand.
///
/// # Errors
/// The diagnostic lists the valid values (or says the role takes none).
pub fn check_framework(
    generator: &dyn DynGenerator,
    req: &GenRequest<'_>,
) -> Result<(), GenDiagnostic> {
    let Some(f) = &req.framework else {
        return Ok(());
    };
    let valid: Vec<String> = generator
        .frameworks(req.role)
        .into_iter()
        .map(|i| i.id)
        .collect();
    if valid.contains(f) {
        return Ok(());
    }
    let expected = if valid.is_empty() {
        format!(
            "the `{}` role of generator `{}` takes no framework",
            req.role.name(),
            generator.id()
        )
    } else {
        format!("expected one of: {}", valid.join(", "))
    };
    Err(GenDiagnostic::new(
        "E0803",
        format!(
            "unknown framework `{f}` for generator `{}` (role `{}`); {expected}",
            generator.id(),
            req.role.name()
        ),
    ))
}

/// Resolves and validates the [`Profile`] of a request: the framework (`E0803`), the language
/// version (`E0802`), the framework version and the language minimum of the adapter (`E0803`).
/// The core calls this before `generate`; a generator never re-validates.
///
/// # Errors
/// The first problem found, with the valid values in the message.
pub fn resolve_profile(
    generator: &dyn DynGenerator,
    req: &GenRequest<'_>,
    options: &serde_json::Value,
) -> Result<Profile, GenDiagnostic> {
    check_framework(generator, req)?;
    let language = generator.language();
    let frameworks = generator.frameworks(req.role);
    let offer = Offer {
        generator: generator.id(),
        role: req.role,
        language: language.as_ref(),
        frameworks: &frameworks,
    };
    Profile::resolve(&offer, req.framework.as_deref(), options)
}

impl<T: Generator> DynGenerator for T {
    fn id(&self) -> &'static str {
        Generator::id(self)
    }
    fn roles(&self) -> &'static [Role] {
        Generator::roles(self)
    }
    fn frameworks(&self, role: Role) -> Vec<FrameworkInfo> {
        Generator::frameworks(self, role)
    }
    fn language(&self) -> Option<LanguageInfo> {
        Generator::language(self)
    }
    fn capabilities(&self, role: Role) -> Capabilities {
        Generator::capabilities(self, role)
    }
    fn generate_dyn(
        &self,
        req: &GenRequest<'_>,
        opts: &serde_json::Value,
    ) -> Result<FileSet, Vec<GenDiagnostic>> {
        let profile = resolve_profile(self, req, opts).map_err(|d| vec![d])?;
        let own = strip_profile_keys(opts, Generator::language(self).as_ref());
        let parsed = if own.is_null() {
            T::Options::default()
        } else {
            serde_json::from_value(own).map_err(|e| {
                vec![GenDiagnostic::new(
                    "E0802",
                    format!(
                        "invalid options for generator `{}`: {e}",
                        Generator::id(self)
                    ),
                )]
            })?
        };
        Generator::generate(self, req, &parsed, &profile)
    }
}

/// `E0801` for every used feature `caps` does not support. The core calls this before `generate`.
#[must_use]
pub fn check_capabilities(
    ir: &Ir,
    req: &GenRequest<'_>,
    caps: &Capabilities,
) -> Vec<GenDiagnostic> {
    let mut all = req.services.clone();
    all.extend(req.consumes.iter().copied());
    ir.features_used(&all)
        .into_iter()
        .filter(|f| !caps.supports(*f))
        .map(|f| GenDiagnostic {
            code: "E0801",
            message: format!(
                "feature `{}` is not supported by this generator for role `{}`",
                f.name(),
                req.role.name()
            ),
            origin: first_use(ir, &all, f),
        })
        .collect()
}

/// Where a feature is first used: an endpoint for endpoint-level features, a declaration otherwise.
fn first_use(ir: &Ir, services: &[ServiceId], feature: Feature) -> Option<Origin> {
    for sid in services {
        for ep in &ir.service(*sid).endpoints {
            let hit = match feature {
                Feature::Auth => ep.auth.kind != veld_ir::AuthKind::None,
                Feature::Middleware => !ep.middleware.is_empty(),
                Feature::StreamingSse | Feature::StreamingWs => {
                    ep.success.stream
                        || ep.method == veld_ir::Method::Ws
                        || ep.params.iter().any(|p| p.stream)
                }
                Feature::Headers => ep
                    .params
                    .iter()
                    .any(|p| p.binding == veld_ir::Binding::Header),
                Feature::Unions
                | Feature::Constraints
                | Feature::Consts
                | Feature::Page
                | Feature::Bytes
                | Feature::RulesInvariants
                | Feature::RulesEndpoint
                | Feature::RulesTransitions
                | Feature::RulesPolicies => false,
            };
            if hit {
                return Some(ep.origin.clone());
            }
        }
    }
    if feature == Feature::RulesInvariants {
        return first_rule_origin(ir, services);
    }
    let wanted_union = feature == Feature::Unions;
    let wanted_const = feature == Feature::Consts;
    ir.reachable_decls(services)
        .into_iter()
        .map(|id| ir.decl(id))
        .find(|d| {
            (wanted_union && matches!(d.kind, DeclKind::Union(_)))
                || (wanted_const && matches!(d.kind, DeclKind::Const(_)))
        })
        .map(|d| d.origin.clone())
}

/// The origin of the first invariant of the first reachable declaration that has one.
fn first_rule_origin(ir: &Ir, services: &[ServiceId]) -> Option<Origin> {
    ir.reachable_decls(services)
        .into_iter()
        .find_map(|id| ir.decl(id).rules().first().map(|r| r.origin.clone()))
}

#[cfg(test)]
mod tests {
    use super::*;
    use veld_ir::*;

    fn ir_with_sse() -> Ir {
        let ep = Endpoint {
            name: "feed".into(),
            method: Method::Get,
            path: "/feed".into(),
            sig: "veld:a/S.feed@0".into(),
            docs: None,
            deprecated: None,
            auth: Auth::none(),
            middleware: vec![],
            params: vec![],
            success: Success {
                status: 200,
                ty: Some(Type::Scalar(Scalar::String)),
                stream: true,
            },
            errors: vec![],
            origin: Origin {
                file: "a.veld".into(),
                line: 3,
                col: 1,
            },
        };
        Ir {
            ir_version: IR_VERSION.into(),
            packages: vec![Package {
                id: PackageId(0),
                name: "a".into(),
                kind: PackageKind::Service,
            }],
            decls: vec![],
            services: vec![Service {
                id: ServiceId(0),
                package: PackageId(0),
                name: "S".into(),
                prefix: "/".into(),
                base_url: None,
                docs: None,
                auth: Auth::none(),
                middleware: vec![],
                endpoints: vec![ep],
                origin: Origin::default(),
            }],
            consumes: Default::default(),
        }
    }

    #[test]
    fn unsupported_feature_reports_e0801_with_origin() {
        let ir = ir_with_sse();
        let req = GenRequest {
            ir: &ir,
            role: Role::Client,
            services: vec![ServiceId(0)],
            consumes: vec![],
            framework: None,
        };
        let caps = Capabilities::all_except(&[Feature::StreamingSse]);
        let diags = check_capabilities(&ir, &req, &caps);
        assert_eq!(diags.len(), 1);
        assert_eq!(diags[0].code, "E0801");
        assert_eq!(diags[0].origin.as_ref().map(|o| o.line), Some(3));
        assert!(check_capabilities(&ir, &req, &Capabilities::all_except(&[])).is_empty());
    }

    #[derive(serde::Deserialize, Default)]
    #[serde(default, deny_unknown_fields)]
    struct Opts {
        flag: bool,
    }
    struct Dummy;
    impl Generator for Dummy {
        type Options = Opts;
        fn id(&self) -> &'static str {
            "dummy"
        }
        fn roles(&self) -> &'static [Role] {
            &[Role::Client, Role::Server]
        }
        fn frameworks(&self, role: Role) -> Vec<FrameworkInfo> {
            let info = |id: &str| FrameworkInfo {
                id: id.to_string(),
                versions: vec![],
                min_language: None,
            };
            match role {
                Role::Server => vec![info("alpha"), info("beta")],
                Role::Client => vec![],
            }
        }
        fn capabilities(&self, _: Role) -> Capabilities {
            Capabilities::default()
        }
        fn generate(
            &self,
            _: &GenRequest<'_>,
            opts: &Opts,
            _: &Profile,
        ) -> Result<FileSet, Vec<GenDiagnostic>> {
            let mut fs = FileSet::new();
            fs.add("flag.txt", if opts.flag { "1" } else { "0" })
                .map_err(|e| vec![GenDiagnostic::new("E0899", e.to_string())])?;
            Ok(fs)
        }
    }

    #[test]
    fn dyn_generator_decodes_options() {
        let ir = ir_with_sse();
        let req = GenRequest {
            ir: &ir,
            role: Role::Client,
            services: vec![],
            consumes: vec![],
            framework: None,
        };
        let g: Box<dyn DynGenerator> = Box::new(Dummy);
        let fs = g
            .generate_dyn(&req, &serde_json::json!({ "flag": true }))
            .unwrap();
        assert_eq!(fs.get("flag.txt"), Some(&b"1"[..]));
        let fs = g.generate_dyn(&req, &serde_json::Value::Null).unwrap();
        assert_eq!(fs.get("flag.txt"), Some(&b"0"[..]));
        let err = g
            .generate_dyn(&req, &serde_json::json!({ "nope": 1 }))
            .unwrap_err();
        assert_eq!(err[0].code, "E0802");
    }

    #[test]
    fn unknown_framework_is_e0803_for_every_role() {
        let ir = ir_with_sse();
        let req = |role, framework: Option<&str>| GenRequest {
            ir: &ir,
            role,
            services: vec![],
            consumes: vec![],
            framework: framework.map(str::to_string),
        };
        let g: Box<dyn DynGenerator> = Box::new(Dummy);
        let null = serde_json::Value::Null;
        // A role with no frameworks rejects any value.
        let err = g
            .generate_dyn(&req(Role::Client, Some("totally-bogus")), &null)
            .unwrap_err();
        assert_eq!(err[0].code, "E0803");
        assert!(
            err[0].message.contains("totally-bogus"),
            "{}",
            err[0].message
        );
        // A role with frameworks lists the valid values.
        let err = g
            .generate_dyn(&req(Role::Server, Some("gamma")), &null)
            .unwrap_err();
        assert_eq!(err[0].code, "E0803");
        assert!(err[0].message.contains("alpha") && err[0].message.contains("beta"));
        assert!(
            g.generate_dyn(&req(Role::Server, Some("beta")), &null)
                .is_ok()
        );
        assert!(g.generate_dyn(&req(Role::Server, None), &null).is_ok());
        assert!(g.generate_dyn(&req(Role::Client, None), &null).is_ok());
    }
}
