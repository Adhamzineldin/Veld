//! A scripted plugin for the host's tests. `--mode <m>` selects a behaviour; see `run`.
//! Not shipped: it exists only so the host can be tested against a real child process.
#![allow(clippy::unwrap_used, clippy::expect_used, clippy::panic, clippy::print_stderr)]

use std::collections::BTreeMap;
use std::io::{BufRead, Write};
use std::time::Duration;

use serde_json::{Value, json};

fn arg(name: &str) -> Option<String> {
    let args: Vec<String> = std::env::args().collect();
    args.iter().position(|a| a == name).and_then(|i| args.get(i + 1).cloned())
}

fn send(v: &Value) {
    let mut out = std::io::stdout().lock();
    writeln!(out, "{v}").unwrap();
    out.flush().unwrap();
}

fn hang() -> ! {
    loop {
        std::thread::sleep(Duration::from_secs(3600));
    }
}

fn hello_reply(mode: &str) -> Value {
    let roles: Vec<String> = arg("--roles").unwrap_or_else(|| "server,client".into()).split(',').map(str::to_string).collect();
    json!({
        "type": "hello",
        "protocol": if mode == "proto2" { "2" } else { "1" },
        "name": "stub",
        "version": arg("--version").unwrap_or_else(|| "1.0.0".into()),
        "roles": roles,
        "capabilities": ["constraints", "auth"],
    })
}

/// One file per declaration and per endpoint, each holding its signature.
fn standard_files(ir: &Value, mode: &str) -> Vec<Value> {
    let mut files = Vec::new();
    for d in ir["decls"].as_array().unwrap() {
        let sig = if mode == "nosig" { "" } else { d["sig"].as_str().unwrap() };
        files.push(json!({"path": format!("types/{}.txt", d["qualified"].as_str().unwrap().replace([':', '/'], "_")), "content": sig}));
    }
    for s in ir["services"].as_array().unwrap() {
        for e in s["endpoints"].as_array().unwrap() {
            let sig = if mode == "nosig" { "" } else { e["sig"].as_str().unwrap() };
            files.push(json!({"path": format!("ops/{}.txt", e["sig"].as_str().unwrap().replace([':', '/', '@'], "_")), "content": sig}));
        }
    }
    files
}

fn result_for(mode: &str, ir: &Value) -> Value {
    let mut files = standard_files(ir, mode);
    match mode {
        "escape" => files = vec![json!({"path": arg("--path").unwrap(), "content": "x"})],
        "nondeterministic" => {
            let nanos = std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).unwrap().as_nanos();
            files.push(json!({"path": "stamp.txt", "content": nanos.to_string()}));
        }
        "env" => {
            let env: BTreeMap<String, String> = std::env::vars().collect();
            let keys: Vec<&String> = env.keys().collect();
            let cwd_entries = std::fs::read_dir(".").unwrap().count();
            files.push(json!({"path": "env.txt", "content": format!("keys={keys:?} cwd_entries={cwd_entries}")}));
            std::fs::write("scratch.txt", "left behind").unwrap();
        }
        "error-diag" => {
            return json!({"type":"result","files":[],"diagnostics":[{"code":"E0801","severity":"error","message":"stub cannot do that","ir_ref":"decl:0"}]});
        }
        _ => {}
    }
    if mode == "banner" {
        files.push(json!({"path": "banner.txt", "content": format!("generated by stub {}", arg("--tag").unwrap_or_default())}));
    }
    json!({"type": "result", "files": files, "diagnostics": []})
}

fn run(mode: &str) {
    eprintln!("stub starting in mode {mode}");
    let stdin = std::io::stdin();
    let mut lines = stdin.lock().lines();
    let Some(Ok(_hello)) = lines.next() else { return };
    if mode == "hang-hello" {
        hang();
    }
    if mode == "garbage-hello" {
        println!("this is not json");
        return;
    }
    send(&hello_reply(mode));
    let Some(Ok(line)) = lines.next() else { return };
    let msg: Value = serde_json::from_str(&line).unwrap();
    match mode {
        "hang-generate" => hang(),
        "crash" => std::process::exit(3),
        _ => {}
    }
    send(&result_for(mode, &msg["ir"]));
    if mode == "exit-after" {
        std::process::exit(3);
    }
    if mode == "linger" {
        hang();
    }
}

fn main() {
    run(&arg("--mode").unwrap_or_else(|| "ok".into()));
}
