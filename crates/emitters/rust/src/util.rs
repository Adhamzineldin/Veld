//! Small shared helpers: identifiers, literals, doc comments and file registration.

use veld_codegen::{CodeWriter, FileSet, GenDiagnostic, naming};

/// First line of every generated Rust file.
pub const HEADER: &str = "// Code generated by veld. DO NOT EDIT.";

/// Rust keywords that can be written as raw identifiers (`r#type`).
const KEYWORDS: &[&str] = &[
    "abstract", "as", "async", "await", "become", "box", "break", "const", "continue", "do", "dyn",
    "else", "enum", "extern", "false", "final", "fn", "for", "gen", "if", "impl", "in", "let",
    "loop", "macro", "match", "mod", "move", "mut", "override", "priv", "pub", "ref", "return",
    "static", "struct", "trait", "true", "try", "type", "typeof", "unsafe", "unsized", "use",
    "virtual", "where", "while", "yield",
];

/// Names that cannot be raw identifiers: they get a trailing `_`.
const NO_RAW: &[&str] = &["self", "Self", "super", "crate", "_"];

/// Names of the standard prelude. A declaration called one of these would shadow it in its own
/// module and break every generated use of the real item, so it gets a trailing `_`.
const PRELUDE: &[&str] = &[
    "AsMut",
    "AsRef",
    "Box",
    "Clone",
    "Copy",
    "Default",
    "Drop",
    "Eq",
    "Err",
    "Extend",
    "Fn",
    "FnMut",
    "FnOnce",
    "From",
    "Into",
    "IntoIterator",
    "Iterator",
    "None",
    "Ok",
    "Option",
    "Ord",
    "PartialEq",
    "PartialOrd",
    "Result",
    "Send",
    "Sized",
    "Some",
    "String",
    "Sync",
    "ToOwned",
    "ToString",
    "Vec",
    "Self",
];

/// Root-level module names the generated crate itself uses.
pub const RESERVED_MODULES: &[&str] = &[
    "adapters",
    "alloc",
    "clients",
    "core",
    "crate",
    "prelude",
    "serde",
    "serde_json",
    "std",
    "veld",
];

/// A valid identifier for `name`: raw for keywords, suffixed where raw is impossible.
#[must_use]
pub fn escape(name: &str) -> String {
    let mut out: String = name
        .chars()
        .map(|c| {
            if c.is_alphanumeric() || c == '_' {
                c
            } else {
                '_'
            }
        })
        .collect();
    if out.is_empty() || out.starts_with(|c: char| c.is_ascii_digit()) {
        out.insert(0, '_');
    }
    if NO_RAW.contains(&out.as_str()) {
        out.push('_');
        out
    } else if KEYWORDS.contains(&out.as_str()) {
        format!("r#{out}")
    } else {
        out
    }
}

/// The identifier without a raw prefix, as serde sees it.
#[must_use]
pub fn bare(ident: &str) -> &str {
    ident.strip_prefix("r#").unwrap_or(ident)
}

/// A `snake_case` identifier (field, parameter, method).
#[must_use]
pub fn snake(name: &str) -> String {
    escape(&naming::snake(name))
}

/// A type name for a declaration: the contract name, unless it would shadow the std prelude.
#[must_use]
pub fn type_name(name: &str) -> String {
    let out = escape(name);
    if PRELUDE.contains(&out.as_str()) {
        format!("{out}_")
    } else {
        out
    }
}

/// An enum variant name in `PascalCase`.
#[must_use]
pub fn variant(name: &str) -> String {
    type_name(&naming::pascal(name))
}

/// A module name for a package or a contract module.
#[must_use]
pub fn module(name: &str) -> String {
    let flat = name.trim_start_matches('@').replace(['/', '.', '-'], "_");
    let mut m = naming::snake(&flat);
    if m.is_empty() {
        m.push('_');
    }
    escape(&m)
}

/// A method name: like [`snake`], and never one of the constructors of the generated clients.
#[must_use]
pub fn method(name: &str) -> String {
    let m = snake(name);
    if matches!(m.as_str(), "new" | "reqwest" | "ureq" | "with_options") {
        format!("{m}_")
    } else {
        m
    }
}

/// A Rust string literal.
#[must_use]
pub fn lit(s: &str) -> String {
    format!("{s:?}")
}

/// JSON text of a string (for schema defaults).
#[must_use]
pub fn json_string(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 => out.push_str(&format!("\\u{:04x}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// Writes `docs` as `///` lines.
pub fn doc(w: &mut CodeWriter, docs: Option<&str>) {
    let Some(docs) = docs else {
        return;
    };
    for line in docs.lines() {
        let line = line.trim_end();
        if line.is_empty() {
            w.line("///");
        } else {
            w.line(format!("/// {line}"));
        }
    }
}

/// Adds a file, mapping a path problem to a diagnostic.
pub fn add_file(
    files: &mut FileSet,
    path: &str,
    text: impl Into<Vec<u8>>,
) -> Result<(), Vec<GenDiagnostic>> {
    files
        .add(path, text)
        .map_err(|e| vec![GenDiagnostic::new("E0805", e.to_string())])
}

/// A diagnostic for a feature the generator cannot represent.
#[must_use]
pub fn unsupported(what: impl Into<String>) -> Vec<GenDiagnostic> {
    vec![GenDiagnostic::new("E0801", what)]
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn identifiers_are_escaped() {
        assert_eq!(snake("type"), "r#type");
        assert_eq!(snake("self"), "self_");
        assert_eq!(snake("customerId"), "customer_id");
        assert_eq!(type_name("Option"), "Option_");
        assert_eq!(type_name("Order"), "Order");
        assert_eq!(method("new"), "new_");
        assert_eq!(bare("r#type"), "type");
        assert_eq!(module("@org/name-x"), "org_name_x");
    }

    #[test]
    fn json_strings_escape() {
        assert_eq!(json_string("a\"b\n"), "\"a\\\"b\\n\"");
    }
}
