//! The files around the code: `Cargo.toml`, `src/lib.rs`, the module declarations and the README.

use std::collections::{BTreeMap, BTreeSet};

use veld_codegen::{FileSet, GenDiagnostic, Role};

use crate::runtime::Features;
use crate::tree::{Tree, is_prelude};
use crate::util::{HEADER, add_file};

/// The module names of a tree: package module to the modules inside it.
fn module_map(
    tree: &Tree<'_>,
    extra: &BTreeMap<veld_ir::ServiceId, Vec<String>>,
) -> BTreeMap<String, BTreeSet<String>> {
    let mut map: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
    for id in tree.decls() {
        let d = tree.ir.decl(*id);
        if is_prelude(tree.ir, d) {
            continue;
        }
        map.entry(tree.pkg_mod(d.package))
            .or_default()
            .insert(Tree::decl_mod(d));
    }
    for sid in &tree.services {
        let svc = tree.ir.service(*sid);
        let entry = map.entry(tree.pkg_mod(svc.package)).or_default();
        for m in extra.get(sid).into_iter().flatten() {
            entry.insert(m.clone());
        }
    }
    for (pkg, file) in crate::policies::Plan::new(tree).modules() {
        map.entry(pkg).or_default().insert(file);
    }
    map
}

/// Emits `<dir>/<pkg>/mod.rs` for every package of a tree, and returns the package module names.
pub fn emit_modules(
    files: &mut FileSet,
    tree: &Tree<'_>,
    service_mods: &BTreeMap<veld_ir::ServiceId, Vec<String>>,
) -> Result<Vec<String>, Vec<GenDiagnostic>> {
    let map = module_map(tree, service_mods);
    for (pkg, mods) in &map {
        let mut text = format!("{HEADER}\n\n");
        for m in mods {
            text.push_str(&format!("pub mod {m};\n"));
        }
        add_file(files, &format!("{}/{pkg}/mod.rs", tree.dir), text)?;
    }
    Ok(map.into_keys().collect())
}

/// `src/lib.rs`.
pub fn emit_lib(
    files: &mut FileSet,
    packages: &[String],
    has_clients: bool,
    f: &Features,
    role: Role,
) -> Result<(), Vec<GenDiagnostic>> {
    let mut s = format!("{HEADER}\n\n");
    s.push_str(&format!(
        "//! Generated by Veld ({} role). See README.md.\n\n",
        role.name()
    ));
    s.push_str(
        "#![allow(\n    clippy::module_inception,\n    clippy::too_many_arguments,\n    clippy::large_enum_variant,\n    clippy::type_complexity,\n    clippy::enum_variant_names\n)]\n\n",
    );
    if f.rules {
        // `veld::Error` carries the rule part of a problem and is now 128 bytes.
        s.push_str("#![allow(clippy::result_large_err)]\n\n");
    }
    s.push_str("pub mod prelude;\n");
    if f.config {
        s.push_str("pub mod runtime_config;\n");
    }
    s.push_str("pub mod veld;\n");
    if f.axum || f.kafka || f.rabbitmq {
        s.push_str("pub mod adapters;\n");
    }
    if has_clients {
        s.push_str("pub mod clients;\n");
    }
    for p in packages {
        s.push_str(&format!("pub mod {p};\n"));
    }
    add_file(files, "src/lib.rs", s)
}

/// The dependency of the Kafka adapter. `default-features = false` drops the `libz`, `zstd` and
/// `ssl` system dependencies of the C library; `cmake-build` builds librdkafka itself.
const RDKAFKA: &str =
    "{ version = \"0.38\", default-features = false, features = [\"cmake-build\", \"tokio\"] }";
/// The dependency of the RabbitMQ adapter.
/// `lapin` with the `tokio` runtime and without TLS: the application enables the TLS feature it needs.
const LAPIN: &str = "{ version = \"4\", default-features = false, features = [\"tokio\"] }";

/// `Cargo.toml`.
pub fn emit_cargo(files: &mut FileSet, name: &str, f: &Features) -> Result<(), Vec<GenDiagnostic>> {
    // `time` for the timeouts of the websocket server and the reqwest transport; `rt` for the
    // task that gives an idempotency key back when a request is dropped (axum already needs tokio).
    let mut tokio: Vec<&str> = Vec::new();
    if f.axum && f.ws_server || f.reqwest {
        tokio.push("\"time\"");
    }
    if f.timeouts && f.server && !tokio.contains(&"\"time\"") {
        tokio.push("\"time\"");
    }
    if f.axum && f.idempotency {
        tokio.push("\"rt\"");
    }
    // The broker adapters wait, spawn and signal with tokio.
    if f.kafka || f.rabbitmq {
        for feature in ["\"macros\"", "\"rt\"", "\"sync\"", "\"time\""] {
            if !tokio.contains(&feature) {
                tokio.push(feature);
            }
        }
    }
    let tokio_spec = format!(
        "{{ version = \"1\", default-features = false, features = [{}] }}",
        tokio.join(", ")
    );
    let mut deps: BTreeMap<&str, &str> = BTreeMap::new();
    deps.insert("serde", "{ version = \"1\", features = [\"derive\"] }");
    deps.insert("serde_json", "\"1\"");
    if f.sse {
        deps.insert("futures-core", "\"0.3\"");
    }
    if f.axum || f.test_events {
        deps.insert(
            "axum",
            if f.ws_server {
                "{ version = \"0.8\", features = [\"ws\"] }"
            } else {
                "\"0.8\""
            },
        );
    }
    if !tokio.is_empty() {
        deps.insert("tokio", &tokio_spec);
    }
    if f.reqwest {
        deps.insert("reqwest", "\"0.13\"");
    }
    if f.reqwest && f.ws_client {
        deps.insert("tokio-tungstenite", "\"0.30\"");
        deps.insert("futures-util", "\"0.3\"");
    }
    if f.ureq {
        deps.insert("ureq", "\"2\"");
    }
    if f.kafka {
        deps.insert("rdkafka", RDKAFKA);
    }
    if f.rabbitmq {
        deps.insert("lapin", LAPIN);
        deps.insert("futures-core", "\"0.3\"");
    }
    let mut s = String::new();
    s.push_str("# Code generated by veld. DO NOT EDIT.\n\n[package]\n");
    s.push_str(&format!("name = \"{name}\"\nversion = \"0.0.0\"\nedition = \"2021\"\nrust-version = \"1.75\"\npublish = false\n"));
    s.push_str("description = \"Generated by Veld. DO NOT EDIT.\"\n\n[dependencies]\n");
    for (k, v) in deps {
        s.push_str(&format!("{k} = {v}\n"));
    }
    add_file(files, "Cargo.toml", s)
}

/// `README.md`.
pub fn emit_readme(
    files: &mut FileSet,
    name: &str,
    role: Role,
    f: &Features,
    runtime: Option<&str>,
) -> Result<(), Vec<GenDiagnostic>> {
    let mut s = format!(
        "# {name}\n\nGenerated by Veld. DO NOT EDIT: run `veld generate` to regenerate. Files listed in\n`.veld-manifest.json` are owned by Veld; an edited file is kept unless you pass `--force`.\n\n"
    );
    s.push_str("## Layout\n\n- `src/veld/`: the runtime (schemas and validation, canonical bytes, identity, problem+json).\n- `src/prelude.rs`: the prelude errors (`NotFound`, `Internal`, `ValidationError`, ...).\n- `src/<package>/<module>.rs`: models, enums, unions, errors and constants of the contract.\n");
    if role == Role::Server {
        if f.server {
            s.push_str(
                "- `src/<package>/<service>_server.rs`: the service trait, hooks and handler.\n",
            );
        }
        if f.events {
            s.push_str("- `src/<package>/<service>_events.rs`: the publisher, the handler trait and `subscribe_<service>_events`.\n- `src/veld/events.rs`: the envelope, the `Transport` trait and `MemoryTransport`.\n");
        }
        if f.axum {
            s.push_str("- `src/adapters/axum.rs`: `router(handler)`, one route per endpoint.\n");
        }
        if f.server {
            s.push_str("\n## Use\n\nImplement `<Service>Service`, build a handler with `<Service>Handler::create(service, hooks)` (or\n`plain(service)` when no hooks are needed) and mount it with `adapters::axum::router(handler)`.\n");
        }
        if f.server && runtime.is_some() {
            s.push_str("\nWith a runtime config, `create` and `plain` take it as their last argument (`&<Target>Runtime`, or an\n`Option` of it when no setting is required) and return `Err(ConfigError)`, with every problem, when it does not pass `check`.\n");
        }
        if f.events {
            s.push_str("\n## Events\n\nA service that publishes gets `create_<service>_publisher(transport, options)`, with one method per\nevent of each channel; a service that subscribes gets `subscribe_<service>_events(transport, handlers, options)`,\nwhere `handlers` implements `<Service>EventHandlers`. `veld::events::MemoryTransport` is the transport that\nships with the crate, for tests and for development: it delivers while a future of `idle()` or `run()` is polled,\nso spawn `transport.run()` once, or await `transport.idle()` in a test.\n");
        }
        if f.endpoint_rules {
            s.push_str("\nA service whose endpoints declare facts (`fact` in an endpoint block) also needs its\n`<Service>FactLoaders`: build the handler with `create(service, hooks, loaders)` (or `plain(service, loaders)`).\nThe service methods of such endpoints receive the loaded facts after the request.\n");
        }
    } else {
        s.push_str("- `src/<package>/<service>_client.rs`: `<Service>Client<T>`, generic over `veld::client::Transport`.\n");
        s.push_str("\n## Use\n\n");
        if f.reqwest {
            s.push_str("`<Service>Client::reqwest(ClientOptions::new().base_url(url))` builds a client on `reqwest`.\n");
        } else if f.ureq {
            s.push_str("`<Service>Client::ureq(options)` builds a blocking client on `ureq`; drive its futures with `veld::block_on`.\n");
        }
        s.push_str("Any other HTTP stack: implement `veld::client::Transport` and use `<Service>Client::new(transport, options)`.\n");
    }
    if let Some(ty) = runtime {
        s.push_str(&format!(
            "\n## Runtime config\n\n`runtime_config::{ty}` holds what a deployment chooses: the URL of each service the target calls and, for a server with rules, `rules.output`. Fill it from any `serde` source, or with `from_value`, `from_map` (paths such as `services.iam.url`) or `from_env` (the names of the variables are yours). `check` reports every problem at once. The generated code reads no environment variable of its own.\n"
        ));
    }
    s.push_str("\n## Identity\n\n`veld::same(&a, &b)` is true when the declaration signatures, the operation signatures (errors) and the\ncanonical bytes are equal. Two different declarations with identical fields are never the same. Across\ncrates use `veld::Identity::of(&a)` and compare the plain data (`veld::same_parts`).\n");
    add_file(files, "README.md", s)
}
