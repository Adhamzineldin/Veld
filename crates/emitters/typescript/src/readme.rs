//! `README.md` of a TypeScript target: how to import the package and how to regenerate it.
//!
//! The text is deterministic and holds no paths, hosts or dates (`CLAUDE.md` rule 2).

use veld_codegen::{FileSet, GenDiagnostic};

use crate::util::add_file;

/// Where the file is written, relative to the target's `out`.
pub const PATH: &str = "README.md";

/// What the README describes.
#[derive(Debug)]
pub struct Readme<'a> {
    /// The npm package name (`@veld/web`).
    pub package: &'a str,
    /// `true` for the `node` server target.
    pub server: bool,
    /// `(key, client class)` of every client the package exports.
    pub clients: &'a [(String, String)],
    /// `(Service, handler factory)` of every service a server implements.
    pub handlers: &'a [(String, String)],
}

/// The exact bytes of `README.md`.
#[must_use]
pub fn render(r: &Readme<'_>) -> String {
    let mut t = format!(
        "# {}\n\nGenerated by Veld. DO NOT EDIT: changes are overwritten by the next `veld generate`.\n\n",
        r.package
    );
    t.push_str("## Import\n\n```ts\n");
    if r.server {
        t.push_str(&server_import(r));
    } else {
        t.push_str(&client_import(r));
    }
    t.push_str("```\n\n");
    t.push_str(&framework_section());
    t.push_str(
        "## Equality\n\n`same(a, b)` compares by declaration signature and canonical bytes, never by \
class. Values decoded by a client, bound by a server or built with `Model.of(...)` carry their \
signature; for plain objects use the companion, `Model.same(a, b)`.\n\n",
    );
    t.push_str(
        "## Regenerate\n\nRun `veld generate` in the project that holds `veld.toml`. The files listed in \
the manifest (`.veld-manifest.json` in this directory) are owned by Veld: a file you edited is \
kept, and generation refuses to overwrite it unless you pass `--force`.\n",
    );
    t
}

fn client_import(r: &Readme<'_>) -> String {
    let names: Vec<&str> = r.clients.iter().map(|(_, c)| c.as_str()).collect();
    let mut s = format!(
        "import {{ createClients, {} }} from '{}';\n\n",
        names.join(", "),
        r.package
    );
    s.push_str("// One client per service, from one set of options:\n");
    s.push_str("const api = createClients({ baseUrl: 'https://api.example.com' });\n");
    if let Some((key, _)) = r.clients.first() {
        s.push_str(&format!("// api.{key}.<endpoint>(request)\n"));
    }
    s
}

fn server_import(r: &Readme<'_>) -> String {
    let mut s = format!("import {{ toExpress, toNodeHttp }} from '{}';\n", r.package);
    for (service, factory) in r.handlers {
        s.push_str(&format!(
            "import {{ {factory}, type {service}Service }} from '{}';\n",
            r.package
        ));
    }
    s.push_str("\n// Implement the service interface and mount the handler with an adapter.\n");
    s
}

fn framework_section() -> String {
    // The same text for every framework: a framework only adds files, it never changes the others.
    "## Framework files\n\nHelpers for the framework you chose (`react`, `vue`, `nest`) are separate files, `<package>/<framework>.ts` or `server/nest/<service>.ts`. They are not in the barrel, so import them explicitly.\n\n".to_string()
}

/// Adds `README.md` to `files`.
pub fn emit(files: &mut FileSet, r: &Readme<'_>) -> Result<(), Vec<GenDiagnostic>> {
    add_file(files, PATH, render(r))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_readme_is_deterministic_and_has_no_paths() {
        let clients = vec![("orders".to_string(), "OrdersClient".to_string())];
        let r = Readme {
            package: "@veld/web",
            server: false,
            clients: &clients,
            handlers: &[],
        };
        let text = render(&r);
        assert_eq!(text, render(&r));
        assert!(text.contains("createClients, OrdersClient"));
        assert!(text.contains("veld generate"));
        assert!(!text.contains(":\\") && !text.contains("/home/") && !text.contains("/Users/"));
    }
}
