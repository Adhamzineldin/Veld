//! `package.json`: makes a generated directory an importable package (`@veld/<target>`).
//!
//! The package is private, has no dependencies, and points `main` and `types` at the
//! TypeScript source barrel. A framework target (`react`, `vue`, `nest`) declares the framework
//! as a `peerDependency` only. `veld setup` wires the package into the consuming app.

use veld_codegen::{FileSet, GenDiagnostic};

use crate::util::add_file;

/// Where the file is written, relative to the target's `out`.
pub const PATH: &str = "package.json";

/// The name used when the generator runs without a target name (direct library use).
pub const DEFAULT_NAME: &str = "@veld/generated";

/// A valid npm package name: lowercase, an optional `@scope/`, URL-safe characters.
#[must_use]
pub fn is_valid_name(name: &str) -> bool {
    fn part_ok(p: &str) -> bool {
        let mut chars = p.chars();
        chars
            .next()
            .is_some_and(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-')
            && chars.all(|c| {
                c.is_ascii_lowercase() || c.is_ascii_digit() || matches!(c, '-' | '.' | '_')
            })
    }
    if name.len() > 214 {
        return false;
    }
    match name.strip_prefix('@') {
        Some(rest) => rest
            .split_once('/')
            .is_some_and(|(scope, pkg)| part_ok(scope) && part_ok(pkg)),
        None => part_ok(name),
    }
}

/// The peer dependency a framework target declares: `(package, range)` pairs.
fn peers(framework: Option<&str>) -> &'static [(&'static str, &'static str)] {
    match framework {
        Some("react") => &[("react", "^18.0.0")],
        Some("vue") => &[("vue", "^3.3.0")],
        Some("nest") => &[("@nestjs/common", "^10.0.0")],
        _ => &[],
    }
}

/// The exact bytes of `package.json`.
#[must_use]
pub fn render(name: &str, framework: Option<&str>) -> String {
    let mut text = format!(
        "{{\n  \"name\": \"{name}\",\n  \"version\": \"0.0.0\",\n  \"private\": true,\n  \
         \"description\": \"Generated by Veld. DO NOT EDIT.\",\n  \"main\": \"index.ts\",\n  \
         \"types\": \"index.ts\",\n  \"sideEffects\": false"
    );
    let peers = peers(framework);
    if !peers.is_empty() {
        text.push_str(",\n  \"peerDependencies\": {\n");
        let lines: Vec<String> = peers
            .iter()
            .map(|(p, v)| format!("    \"{p}\": \"{v}\""))
            .collect();
        text.push_str(&lines.join(",\n"));
        text.push_str("\n  }");
    }
    text.push_str("\n}\n");
    text
}

/// Adds `package.json` to `files`. `name` is the `package-name` option, or the default.
pub fn emit(
    files: &mut FileSet,
    name: Option<&str>,
    framework: Option<&str>,
) -> Result<(), Vec<GenDiagnostic>> {
    let name = name.unwrap_or(DEFAULT_NAME);
    if !is_valid_name(name) {
        return Err(vec![GenDiagnostic::new(
            "E0802",
            format!(
                "option `package-name` = `{name}` is not a valid npm package name (lowercase letters, digits, `-`, `.`, `_`, optionally `@scope/`)"
            ),
        )]);
    }
    add_file(files, PATH, render(name, framework))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names_are_validated() {
        for ok in ["@veld/api", "@veld/orders-api", "plain", "@a/b.c_d"] {
            assert!(is_valid_name(ok), "{ok}");
        }
        for bad in [
            "", "@veld", "@veld/", "Veld", "@veld/A", "a b", "@/x", "../x", ".x",
        ] {
            assert!(!is_valid_name(bad), "{bad}");
        }
    }

    #[test]
    fn plain_package_has_no_dependencies() {
        let text = render("@veld/api", None);
        assert!(!text.contains("ependencies"), "{text}");
        assert!(text.contains("\"private\": true") && text.contains("\"main\": \"index.ts\""));
        assert_eq!(text, render("@veld/api", None));
    }

    #[test]
    fn frameworks_are_peer_dependencies_only() {
        for (fw, dep) in [
            ("react", "react"),
            ("vue", "vue"),
            ("nest", "@nestjs/common"),
        ] {
            let text = render("@veld/web", Some(fw));
            assert!(text.contains("\"peerDependencies\""), "{text}");
            assert!(text.contains(&format!("\"{dep}\"")), "{text}");
            assert!(!text.contains("\"dependencies\""), "{text}");
            assert!(text.ends_with("}\n"));
        }
        assert!(!render("@veld/api", Some("express")).contains("peerDependencies"));
    }

    #[test]
    fn an_invalid_name_is_e0802() {
        let mut files = FileSet::new();
        let err = emit(&mut files, Some("Bad Name"), None).unwrap_err();
        assert_eq!(err[0].code, "E0802");
    }
}
