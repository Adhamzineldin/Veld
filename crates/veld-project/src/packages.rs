//! Registry packages on disk: the `veld.lock` file and the project-local package cache.
//!
//! The cache lives at `<root>/.veld/packages/@org/name/<version>/` and holds the unpacked
//! package (`contracts/**.veld` and `veld-package.toml`). Installing is the job of
//! `veld-registry-client`; this module only reads what is installed.

use std::collections::{BTreeMap, BTreeSet};
use std::path::{Path, PathBuf};

use serde::{Deserialize, Serialize};
use thiserror::Error;
use veld_ir::PackageKind;

use crate::config::{PackageSpec, Project, collect_sources};

/// The registry lock file, next to `veld.toml`.
pub const LOCK_FILE: &str = "veld.lock";
/// The package cache, relative to the project root.
pub const CACHE_DIR: &str = ".veld/packages";
/// Directory inside an unpacked package that holds its `.veld` files.
pub const CONTRACTS_DIR: &str = "contracts";
/// The manifest at the root of every package.
pub const MANIFEST_FILE: &str = "veld-package.toml";

#[derive(Debug, Error)]
pub enum PackagesError {
    #[error("cannot read `{}`: {source}", path.display())]
    Io {
        path: PathBuf,
        source: std::io::Error,
    },
    #[error("invalid {LOCK_FILE}: {0}")]
    Lock(String),
    #[error("{0}")]
    Config(#[from] crate::config::ConfigError),
}

/// One pinned package in `veld.lock`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct LockedPackage {
    /// `@org/name`.
    pub name: String,
    pub version: String,
    /// SHA-256 (hex) of the package tarball.
    pub sha256: String,
    /// The registry the package was resolved from.
    pub registry: String,
    /// Names of the packages this one depends on (its own `[dependencies]`), sorted. Each is
    /// also an entry of the lock: the lock holds the whole graph, one version per package.
    #[serde(default)]
    pub dependencies: Vec<String>,
}

/// The contents of `veld.lock`.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Lockfile {
    pub packages: Vec<LockedPackage>,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct RawLock {
    #[serde(default)]
    version: Option<u32>,
    #[serde(default, rename = "package")]
    packages: Vec<LockedPackage>,
}

const HEADER: &str = "# This file is generated by `veld add` and `veld install`. Do not edit it.\n";

impl Lockfile {
    /// Parses lock text. Rejects unknown versions and duplicate packages.
    pub fn parse(text: &str) -> Result<Self, PackagesError> {
        let raw: RawLock = toml::from_str(text).map_err(|e| PackagesError::Lock(e.to_string()))?;
        if raw.version.is_some_and(|v| v != 1) {
            return Err(PackagesError::Lock(
                "unsupported lock version (this veld reads version 1)".into(),
            ));
        }
        let mut lock = Lockfile {
            packages: raw.packages,
        };
        lock.packages.sort_by(|a, b| a.name.cmp(&b.name));
        for p in &mut lock.packages {
            p.dependencies.sort();
            p.dependencies.dedup();
        }
        if let Some(w) = lock.packages.windows(2).find(|w| w[0].name == w[1].name) {
            return Err(PackagesError::Lock(format!(
                "package `{}` is listed twice",
                w[0].name
            )));
        }
        lock.check_closed()?;
        Ok(lock)
    }

    /// Every dependency of a locked package must itself be locked (the lock is the whole graph).
    fn check_closed(&self) -> Result<(), PackagesError> {
        for p in &self.packages {
            if let Some(missing) = p.dependencies.iter().find(|d| self.get(d).is_none()) {
                return Err(PackagesError::Lock(format!(
                    "`{}` depends on `{missing}`, which is not in the lock",
                    p.name
                )));
            }
        }
        Ok(())
    }

    /// Reads `<root>/veld.lock`; `Ok(None)` when there is none.
    pub fn read(root: &Path) -> Result<Option<Self>, PackagesError> {
        let path = root.join(LOCK_FILE);
        match std::fs::read_to_string(&path) {
            Ok(text) => Self::parse(&text).map(Some),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
            Err(source) => Err(PackagesError::Io { path, source }),
        }
    }

    /// Deterministic text: packages sorted by name, fixed key order, trailing newline.
    pub fn to_toml(&self) -> String {
        let mut sorted: Vec<&LockedPackage> = self.packages.iter().collect();
        sorted.sort_by(|a, b| a.name.cmp(&b.name));
        let mut out = String::from(HEADER);
        out.push_str("version = 1\n");
        for p in sorted {
            out.push_str("\n[[package]]\n");
            for (k, v) in [
                ("name", &p.name),
                ("version", &p.version),
                ("sha256", &p.sha256),
                ("registry", &p.registry),
            ] {
                out.push_str(&format!("{k} = {}\n", toml_string(v)));
            }
            let mut deps: Vec<&String> = p.dependencies.iter().collect();
            deps.sort();
            let list: Vec<String> = deps.into_iter().map(|d| toml_string(d)).collect();
            out.push_str(&format!("dependencies = [{}]\n", list.join(", ")));
        }
        out
    }

    pub fn get(&self, name: &str) -> Option<&LockedPackage> {
        self.packages.iter().find(|p| p.name == name)
    }
}

fn toml_string(s: &str) -> String {
    toml::Value::String(s.to_string()).to_string()
}

/// Splits `@org/name`. Both parts must be non-empty and path safe.
pub fn split_name(name: &str) -> Option<(&str, &str)> {
    let rest = name.strip_prefix('@')?;
    let (org, pkg) = rest.split_once('/')?;
    let ok = |s: &str| {
        !s.is_empty()
            && s != "."
            && s != ".."
            && s.bytes()
                .all(|b| b.is_ascii_alphanumeric() || matches!(b, b'-' | b'_' | b'.'))
    };
    (ok(org) && ok(pkg)).then_some((org, pkg))
}

/// `<root>/.veld/packages/@org/name/<version>`. `None` for an unsafe name or version.
pub fn cache_dir(root: &Path, name: &str, version: &str) -> Option<PathBuf> {
    let (org, pkg) = split_name(name)?;
    let version_ok = !version.is_empty()
        && version
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || matches!(b, b'-' | b'.' | b'+'));
    version_ok.then(|| {
        root.join(CACHE_DIR)
            .join(format!("@{org}"))
            .join(pkg)
            .join(version)
    })
}

/// A package that is pinned in the lock and present in the cache.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct InstalledPackage {
    pub name: String,
    pub version: String,
    /// Absolute directory holding the package's `.veld` files.
    pub contracts: PathBuf,
}

/// What the lock pins versus what the cache holds.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct InstallState {
    pub installed: Vec<InstalledPackage>,
    /// Pinned packages that are not in the cache.
    pub missing: Vec<LockedPackage>,
}

/// Compares `veld.lock` with the cache under `root`. No lock means nothing is installed.
pub fn install_state(root: &Path) -> Result<InstallState, PackagesError> {
    let mut state = InstallState::default();
    let Some(lock) = Lockfile::read(root)? else {
        return Ok(state);
    };
    for p in &lock.packages {
        let dir = cache_dir(root, &p.name, &p.version).ok_or_else(|| {
            PackagesError::Lock(format!(
                "unsafe package `{}` version `{}`",
                p.name, p.version
            ))
        })?;
        let contracts = dir.join(CONTRACTS_DIR);
        if dir.join(MANIFEST_FILE).is_file() && contracts.is_dir() {
            state.installed.push(InstalledPackage {
                name: p.name.clone(),
                version: p.version.clone(),
                contracts,
            });
        } else {
            state.missing.push(p.clone());
        }
    }
    Ok(state)
}

/// An installed registry package with its sources, ready for the compiler.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RegistryPackage {
    pub name: String,
    pub version: String,
    /// `(path relative to the contracts dir, text)`, sorted by path.
    pub sources: Vec<(String, String)>,
}

impl Project {
    /// The installed registry packages, named `@org/name`, with their sources. Packages that
    /// are pinned but not installed are left out; `veld install` provides them.
    pub fn registry_packages(&self) -> Result<Vec<RegistryPackage>, PackagesError> {
        let state = install_state(&self.root)?;
        let mut out = Vec::new();
        for p in state.installed {
            let spec = PackageSpec {
                name: p.name.clone(),
                kind: PackageKind::Registry,
                root: p.contracts,
                base_url: None,
                consumes: Vec::new(),
                prefix: String::new(),
            };
            out.push(RegistryPackage {
                name: p.name,
                version: p.version,
                sources: collect_sources(&spec)?,
            });
        }
        Ok(out)
    }

    /// Which registry packages each package may `use`, for the compiler's access check:
    /// every project package may use the project's direct `[dependencies]`; every locked
    /// registry package may use the dependencies the lock records for it. Keyed by package name.
    pub fn registry_access(&self) -> Result<BTreeMap<String, BTreeSet<String>>, PackagesError> {
        let direct: BTreeSet<String> = self.dependencies.keys().cloned().collect();
        let mut out: BTreeMap<String, BTreeSet<String>> = self
            .packages
            .iter()
            .map(|p| (p.name.clone(), direct.clone()))
            .collect();
        if let Some(lock) = Lockfile::read(&self.root)? {
            for p in lock.packages {
                out.insert(p.name, p.dependencies.into_iter().collect());
            }
        }
        Ok(out)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn pkg(name: &str, version: &str) -> LockedPackage {
        LockedPackage {
            name: name.into(),
            version: version.into(),
            sha256: "ab".repeat(32),
            registry: "https://r.example".into(),
            dependencies: Vec::new(),
        }
    }

    #[test]
    fn lock_round_trips_and_is_sorted() {
        let lock = Lockfile {
            packages: vec![pkg("@z/last", "1.0.0"), pkg("@a/first", "2.1.0-beta.1")],
        };
        let text = lock.to_toml();
        assert!(text.find("@a/first").unwrap() < text.find("@z/last").unwrap());
        let back = Lockfile::parse(&text).unwrap();
        assert_eq!(back.packages.len(), 2);
        assert_eq!(back.to_toml(), text, "serialising is stable");
        assert_eq!(back.get("@z/last").unwrap().version, "1.0.0");
    }

    #[test]
    fn lock_rejects_bad_input() {
        assert!(Lockfile::parse("version = 2\n").is_err());
        assert!(Lockfile::parse("bogus = 1\n").is_err());
        let one = Lockfile {
            packages: vec![pkg("@a/b", "1.0.0")],
        };
        let dup = format!(
            "{}\n[[package]]\nname = \"@a/b\"\nversion = \"1.0.1\"\nsha256 = \"x\"\nregistry = \"r\"\n",
            one.to_toml()
        );
        assert!(Lockfile::parse(&dup).is_err());
    }

    #[test]
    fn names_are_validated() {
        assert_eq!(split_name("@acme/billing"), Some(("acme", "billing")));
        for bad in [
            "acme/billing",
            "@acme",
            "@/x",
            "@a/..",
            "@../x",
            "@a/b/c",
            "@a/b\\c",
        ] {
            assert_eq!(split_name(bad), None, "{bad}");
        }
        assert!(cache_dir(Path::new("/r"), "@a/b", "../x").is_none());
        assert!(cache_dir(Path::new("/r"), "@a/b", "1.0.0").is_some());
    }

    #[test]
    fn install_state_reports_installed_and_missing() {
        let tmp = tempfile::tempdir().unwrap();
        let root = tmp.path();
        assert_eq!(install_state(root).unwrap(), InstallState::default());
        let lock = Lockfile {
            packages: vec![pkg("@a/here", "1.0.0"), pkg("@a/gone", "1.0.0")],
        };
        std::fs::write(root.join(LOCK_FILE), lock.to_toml()).unwrap();
        let dir = cache_dir(root, "@a/here", "1.0.0").unwrap();
        std::fs::create_dir_all(dir.join(CONTRACTS_DIR)).unwrap();
        std::fs::write(dir.join(MANIFEST_FILE), "").unwrap();
        std::fs::write(dir.join(CONTRACTS_DIR).join("m.veld"), "model M {}").unwrap();
        let state = install_state(root).unwrap();
        assert_eq!(state.installed.len(), 1);
        assert_eq!(state.missing[0].name, "@a/gone");
    }

    fn with_deps(mut p: LockedPackage, deps: &[&str]) -> LockedPackage {
        p.dependencies = deps.iter().map(|d| (*d).to_string()).collect();
        p
    }

    #[test]
    fn lock_records_dependencies_and_round_trips() {
        let lock = Lockfile {
            packages: vec![
                with_deps(pkg("@acme/billing", "1.0.0"), &["@acme/money", "@acme/ids"]),
                pkg("@acme/money", "1.2.0"),
                pkg("@acme/ids", "1.0.0"),
            ],
        };
        let text = lock.to_toml();
        assert!(
            text.contains("dependencies = [\"@acme/ids\", \"@acme/money\"]"),
            "sorted: {text}"
        );
        assert!(text.contains("dependencies = []"));
        let back = Lockfile::parse(&text).unwrap();
        assert_eq!(
            back.get("@acme/billing").unwrap().dependencies,
            ["@acme/ids", "@acme/money"]
        );
        assert_eq!(back.to_toml(), text, "stable");
    }

    #[test]
    fn old_locks_without_dependencies_still_parse() {
        let old = "version = 1\n\n[[package]]\nname = \"@a/b\"\nversion = \"1.0.0\"\nsha256 = \"x\"\nregistry = \"r\"\n";
        assert!(
            Lockfile::parse(old).unwrap().packages[0]
                .dependencies
                .is_empty()
        );
    }

    #[test]
    fn lock_must_be_closed_but_may_have_cycles() {
        let dangling = Lockfile {
            packages: vec![with_deps(pkg("@a/x", "1.0.0"), &["@a/missing"])],
        };
        let err = Lockfile::parse(&dangling.to_toml())
            .unwrap_err()
            .to_string();
        assert!(err.contains("@a/missing"), "{err}");
        let cycle = Lockfile {
            packages: vec![
                with_deps(pkg("@a/x", "1.0.0"), &["@a/y"]),
                with_deps(pkg("@a/y", "1.0.0"), &["@a/x"]),
            ],
        };
        assert!(Lockfile::parse(&cycle.to_toml()).is_ok());
    }

    #[test]
    fn access_rules_follow_the_lock() {
        let tmp = tempfile::tempdir().unwrap();
        let root = tmp.path();
        std::fs::create_dir_all(root.join("contracts")).unwrap();
        std::fs::write(
            root.join("veld.toml"),
            "[service]\nname = \"app\"\n[dependencies]\n\"@acme/billing\" = \"^1\"\n",
        )
        .unwrap();
        let lock = Lockfile {
            packages: vec![
                with_deps(pkg("@acme/billing", "1.0.0"), &["@acme/money"]),
                pkg("@acme/money", "1.0.0"),
            ],
        };
        std::fs::write(root.join(LOCK_FILE), lock.to_toml()).unwrap();
        let project = crate::config::load(&root.join("veld.toml")).unwrap();
        let access = project.registry_access().unwrap();
        assert_eq!(access["app"], BTreeSet::from(["@acme/billing".to_string()]));
        assert_eq!(
            access["@acme/billing"],
            BTreeSet::from(["@acme/money".to_string()])
        );
        assert!(access["@acme/money"].is_empty());
    }
}
