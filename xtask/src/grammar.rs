//! The TextMate grammar of Veld, generated from `editors/veld-language.json` so that the
//! keyword lists can never drift from the compiler's language table.

use anyhow::{Context, Result};
use serde_json::{Value, json};

fn words(spec: &Value, key: &str) -> Vec<String> {
    spec[key]
        .as_array()
        .map(|a| {
            a.iter()
                .filter_map(|v| v.as_str().map(str::to_string))
                .collect()
        })
        .unwrap_or_default()
}

/// `\b(a|b|c)\b`
fn alternation(list: &[String]) -> String {
    format!("\\b({})\\b", list.join("|"))
}

/// Names of the `error X ...` declarations in the prelude source.
fn prelude_errors(spec: &Value) -> Vec<String> {
    spec["prelude"]
        .as_str()
        .unwrap_or_default()
        .lines()
        .filter_map(|l| l.strip_prefix("error "))
        .filter_map(|l| l.split_whitespace().next())
        .map(str::to_string)
        .collect()
}

/// Builds the grammar text from the language table (`editors/veld-language.json`).
pub fn tm_language(language_json: &str) -> Result<String> {
    let spec: Value =
        serde_json::from_str(language_json).context("editors/veld-language.json is not JSON")?;
    let reserved = words(&spec, "reserved");
    let contextual = words(&spec, "contextual");
    // Contextual words of the rules language that read as operators between two operands.
    let rule_words = words(&spec, "rule_words");
    let word_operators: Vec<String> = ["implies", "not", "in"]
        .iter()
        .filter(|w| rule_words.iter().any(|r| r == *w))
        .map(|w| (*w).to_string())
        .collect();
    let scalars = words(&spec, "scalars");
    let generics = words(&spec, "generics");
    let annotations: Vec<String> = spec["annotations"]
        .as_array()
        .map(|a| {
            a.iter()
                .filter_map(|x| x["name"].as_str().map(str::to_string))
                .collect()
        })
        .unwrap_or_default();
    let literals = ["true", "false", "null"];
    let keywords: Vec<String> = reserved
        .iter()
        .filter(|w| !literals.contains(&w.as_str()))
        .cloned()
        .collect();
    let errors = prelude_errors(&spec);
    let grammar = json!({
        "$schema": "https://raw.githubusercontent.com/martinring/tmlanguage/master/tmlanguage.json",
        "name": "Veld",
        "scopeName": "source.veld",
        "fileTypes": ["veld"],
        "comment": "Generated by `cargo xtask codegen` from editors/veld-language.json. Do not edit.",
        "patterns": [
            {"include": "#comments"},
            {"include": "#strings"},
            {"include": "#annotations"},
            {"include": "#declarations"},
            {"include": "#use"},
            {"include": "#arrow"},
            {"include": "#rules"},
            {"include": "#methods"},
            {"include": "#literals"},
            {"include": "#variants"},
            {"include": "#keywords"},
            {"include": "#types"},
            {"include": "#fields"}
        ],
        "repository": {
            "comments": {"patterns": [
                {"name": "comment.line.documentation.veld", "match": "///.*$"},
                {"name": "comment.line.double-slash.veld", "match": "//.*$"}
            ]},
            "strings": {
                "name": "string.quoted.double.veld",
                "begin": "\"",
                "end": "\"",
                "patterns": [
                    {"name": "constant.character.escape.veld", "match": "\\\\."},
                    {"name": "variable.parameter.path.veld", "match": "\\{[A-Za-z_][A-Za-z0-9_]*\\}"}
                ]
            },
            "annotations": {"patterns": [
                {
                    "name": "entity.other.attribute-name.annotation.veld",
                    "match": format!("@({})\\b", annotations.join("|"))
                },
                {"name": "invalid.illegal.unknown-annotation.veld", "match": "@[A-Za-z_][A-Za-z0-9_]*"}
            ]},
            "declarations": {"patterns": [
                {
                    "match": "\\b(model|enum|error|union|service|const)\\s+([A-Za-z_][A-Za-z0-9_]*)",
                    "captures": {
                        "1": {"name": "storage.type.declaration.veld"},
                        "2": {"name": "entity.name.type.veld"}
                    }
                },
                {
                    "match": "\\b(extends)\\s+([A-Za-z_][A-Za-z0-9_]*)",
                    "captures": {
                        "1": {"name": "storage.modifier.veld"},
                        "2": {"name": "entity.other.inherited-class.veld"}
                    }
                }
            ]},
            "use": {
                "match": "^\\s*(use)\\s+(?:(@?[A-Za-z0-9_/]+)(:))?([A-Za-z_][A-Za-z0-9_.]*)",
                "captures": {
                    "1": {"name": "keyword.control.import.veld"},
                    "2": {"name": "entity.name.namespace.package.veld"},
                    "3": {"name": "punctuation.separator.veld"},
                    "4": {"name": "entity.name.namespace.module.veld"}
                }
            },
            "arrow": {"name": "keyword.operator.arrow.veld", "match": "->|\\|"},
            "rules": {"patterns": [
                {
                    "match": "^\\s*(rule)\\s+([A-Za-z_][A-Za-z0-9_]*)(?=\\s*:)",
                    "captures": {
                        "1": {"name": "keyword.control.rule.veld"},
                        "2": {"name": "entity.name.function.rule.veld"}
                    }
                },
                {
                    "match": "^\\s*(message)(?=\\s+\")",
                    "captures": {"1": {"name": "keyword.control.rule.veld"}}
                },
                {"name": "keyword.operator.word.veld", "match": format!("(?<=\\s)({})(?=\\s)", word_operators.join("|"))},
                {"name": "support.function.builtin.veld", "match": "\\b(has)(?=\\()"},
                {"name": "keyword.operator.logical.veld", "match": "&&|\\|\\||==|!=|<=|>=|=>"}
            ]},
            "methods": {
                "name": "keyword.control.http-method.veld",
                "match": format!("^\\s*{}(?=\\s+\")", alternation(&contextual))
            },
            "literals": {"patterns": [
                {"name": "constant.language.veld", "match": alternation(&literals.map(str::to_string))},
                {"name": "constant.numeric.veld", "match": "\\b-?\\d+(\\.\\d+)?\\b"}
            ]},
            "variants": {
                "name": "constant.other.enum-member.veld",
                "match": "(?<=[=\\s])\\.[A-Za-z_][A-Za-z0-9_]*"
            },
            "keywords": {
                "name": "keyword.other.veld",
                "match": alternation(&keywords)
            },
            "types": {"patterns": [
                {"name": "support.type.primitive.veld", "match": alternation(&scalars)},
                {"name": "support.type.generic.veld", "match": alternation(&generics)},
                {"name": "support.class.error.veld", "match": alternation(&errors)},
                {"name": "entity.name.type.reference.veld", "match": "\\b[A-Z][A-Za-z0-9_]*\\b"}
            ]},
            "fields": {
                "match": "\\b([a-z_][A-Za-z0-9_]*)(\\??)\\s*(?=:)",
                "captures": {
                    "1": {"name": "variable.other.property.veld"},
                    "2": {"name": "keyword.operator.optional.veld"}
                }
            }
        }
    });
    let mut text =
        serde_json::to_string_pretty(&grammar).context("cannot serialize the grammar")?;
    text.push('\n');
    Ok(text)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn grammar() -> Value {
        let language = serde_json::to_string(&veld_compiler::language::spec()).unwrap();
        serde_json::from_str(&tm_language(&language).unwrap()).unwrap()
    }

    #[test]
    fn keywords_come_from_the_language_table() {
        let g = grammar();
        let kw = g["repository"]["keywords"]["match"].as_str().unwrap();
        for w in ["use", "model", "extends", "stream"] {
            assert!(kw.contains(w), "{kw}");
        }
        assert!(!kw.contains("true"), "literals are scoped separately");
        let methods = g["repository"]["methods"]["match"].as_str().unwrap();
        assert!(methods.contains("get") && methods.contains("ws"));
        let ann = g["repository"]["annotations"]["patterns"][0]["match"]
            .as_str()
            .unwrap();
        assert!(ann.starts_with("@(auth|"), "{ann}");
        let types = g["repository"]["types"]["patterns"][2]["match"]
            .as_str()
            .unwrap();
        assert!(types.contains("NotFound"), "{types}");
    }

    #[test]
    fn every_regex_compiles_in_the_shared_subset() {
        // Balanced groups are the cheap sanity check available without a regex engine here.
        fn walk(v: &Value, out: &mut Vec<String>) {
            match v {
                Value::Object(m) => {
                    for (k, x) in m {
                        if matches!(k.as_str(), "match" | "begin" | "end") {
                            out.extend(x.as_str().map(str::to_string));
                        }
                        walk(x, out);
                    }
                }
                Value::Array(a) => a.iter().for_each(|x| walk(x, out)),
                Value::Null | Value::Bool(_) | Value::Number(_) | Value::String(_) => {}
            }
        }
        let mut all = Vec::new();
        walk(&grammar(), &mut all);
        assert!(all.len() > 10);
        for r in all {
            let opens = r.matches('(').count() - r.matches("\\(").count();
            let closes = r.matches(')').count() - r.matches("\\)").count();
            assert_eq!(opens, closes, "{r}");
        }
    }
}
